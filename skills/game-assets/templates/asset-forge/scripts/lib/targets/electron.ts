import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { sha256 } from '../manifest';
import type { TargetExporter } from '../types';

/** Destination keeps <category>/<file>; the project folder is the game's own, so it is dropped. */
export function destRelPath(category: string, file: string): string {
  return category ? `${category}/${file}` : file;
}

export const electronTarget: TargetExporter = {
  async exportAsset(ctx, entry) {
    const dest = destRelPath(entry.category, entry.file);
    const from = join(ctx.assetsDir, entry.relPath);
    const to = join(ctx.destDir, dest);
    mkdirSync(dirname(to), { recursive: true });
    copyFileSync(from, to);
    const bytes = readFileSync(from);
    return { name: entry.name, path: entry.relPath, sha256: sha256(bytes), bytes: bytes.length, dest };
  },

  async finalize(ctx, manifest) {
    const lines = manifest.assets.map((a) => `  ${a.name}: './${a.dest ?? ''}',`);
    const source = [
      '// Generated by asset-forge. Do not edit.',
      'export const ASSETS = {',
      ...lines,
      '} as const;',
      '',
      'export type AssetName = keyof typeof ASSETS;',
      '',
    ].join('\n');
    mkdirSync(ctx.destDir, { recursive: true });
    writeFileSync(join(ctx.destDir, 'assets.ts'), source);
  },
};
