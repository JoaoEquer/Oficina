import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { sha256 } from '../manifest';
import { readCache, writeCache } from '../roblox-cache';
import type { ExportContext, TargetExporter } from '../types';

const API = 'https://apis.roblox.com/assets/v1';
const MAX_POLLS = 30;
const POLL_MS = 1000;
const DISPLAY_NAME_MAX = 50;

const MIME: Record<string, string> = { png: 'image/png', jpg: 'image/jpeg', jpeg: 'image/jpeg' };

interface Credentials {
  apiKey: string;
  creatorId: string;
  creatorType: 'User' | 'Group';
}

/** Never put the key in an error message. */
export function readCredentials(env: ExportContext['env']): Credentials {
  const apiKey = env.ROBLOX_API_KEY;
  const creatorId = env.ROBLOX_CREATOR_ID;
  if (!apiKey || !creatorId) {
    throw new Error('Roblox target needs ROBLOX_API_KEY and ROBLOX_CREATOR_ID in .env (see .env.example).');
  }
  const creatorType = env.ROBLOX_CREATOR_TYPE === 'Group' ? 'Group' : 'User';
  return { apiKey, creatorId, creatorType };
}

interface OperationResponse {
  path?: string;
  done?: boolean;
  response?: { assetId?: string };
  error?: { message?: string };
}

async function readJson(res: Response, action: string): Promise<OperationResponse> {
  if (!res.ok) throw new Error(`Roblox ${action} failed: HTTP ${res.status}`);
  return (await res.json()) as OperationResponse;
}

export function buildUploadRequest(name: string, creds: Credentials): string {
  const creator = creds.creatorType === 'Group' ? { groupId: creds.creatorId } : { userId: creds.creatorId };
  return JSON.stringify({
    assetType: 'Decal',
    displayName: name.slice(0, DISPLAY_NAME_MAX),
    description: 'Uploaded by asset-forge',
    creationContext: { creator },
  });
}

async function uploadAsset(ctx: ExportContext, creds: Credentials, name: string, file: string, bytes: Buffer): Promise<string> {
  const ext = file.slice(file.lastIndexOf('.') + 1).toLowerCase();
  const form = new FormData();
  form.append('request', buildUploadRequest(name, creds));
  form.append('fileContent', new Blob([new Uint8Array(bytes)], { type: MIME[ext] ?? 'image/png' }), basename(file));

  const created = await readJson(
    await ctx.fetchImpl(`${API}/assets`, { method: 'POST', headers: { 'x-api-key': creds.apiKey }, body: form }),
    `upload of ${name}`,
  );
  const operationId = created.path?.split('/')[1];
  if (!operationId) throw new Error(`Roblox upload of ${name} returned no operation.`);

  for (let attempt = 0; attempt < MAX_POLLS; attempt += 1) {
    const op = await readJson(
      await ctx.fetchImpl(`${API}/operations/${operationId}`, { headers: { 'x-api-key': creds.apiKey } }),
      `status of ${name}`,
    );
    if (op.done) {
      const assetId = op.response?.assetId;
      if (!assetId) throw new Error(`Roblox rejected ${name}: ${op.error?.message ?? 'no assetId in response'}`);
      return assetId;
    }
    await ctx.sleep(POLL_MS);
  }
  throw new Error(`Roblox upload of ${name} did not finish after ${MAX_POLLS} checks.`);
}

export const robloxTarget: TargetExporter = {
  async exportAsset(ctx, entry) {
    const bytes = readFileSync(join(ctx.assetsDir, entry.relPath));
    const hash = sha256(bytes);
    const cache = readCache(ctx.forgeDir);

    let assetId = cache[hash];
    if (!assetId) {
      assetId = await uploadAsset(ctx, readCredentials(ctx.env), entry.name, entry.file, bytes);
      writeCache(ctx.forgeDir, { ...cache, [hash]: assetId });
    }
    return { name: entry.name, path: entry.relPath, sha256: hash, bytes: bytes.length, assetId };
  },

  /** Rojo-compatible ModuleScript: require it and index by asset name. */
  async finalize(ctx, manifest) {
    const lines = manifest.assets
      .filter((a) => a.assetId)
      .map((a) => `\t${a.name} = "rbxassetid://${a.assetId}",`);
    const source = [
      '-- Generated by asset-forge. Do not edit.',
      '-- ImageLabel/ImageButton: set ResampleMode = Enum.ResamplerMode.Pixelated for pixel art.',
      'return {',
      ...lines,
      '}',
      '',
    ].join('\n');
    mkdirSync(ctx.destDir, { recursive: true });
    writeFileSync(join(ctx.destDir, 'Assets.lua'), source);
  },
};
